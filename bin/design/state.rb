# Regenerates the "Current state" table in docs/changelog.md.
#
#     bin/rails runner bin/design/state.rb          # rewrite the table
#     bin/rails runner bin/design/state.rb --check  # exit 1 if it is out of date, change nothing
#
# **Why this exists.** The table was hand-maintained and went stale the moment anyone stopped
# typing: refreshed on 2026-09-03, wrong by 42 commits two days later, and before that it had drifted
# far enough that `migration-map.md` carried a second copy disagreeing with it. Every figure here is
# already computed by something; the only reason they went out of date is that a person had to copy
# them. Now nobody does.
#
# It rewrites only what is between the markers. The prose around the table -- what the numbers mean,
# which of them is not what it looks like -- is judgement and stays hand-written, because a generator
# has nothing to say about that.
#
# `--check` is what CI would run: it fails when the committed table no longer matches the tree, which
# is the same discipline as a schema dump.
require "json"

BEGIN_MARK = "<!-- state:begin -->".freeze
END_MARK = "<!-- state:end -->".freeze
CHANGELOG = Rails.root.join("docs/changelog.md")

# Shell out rather than reimplement. Each of these is the definition of its own number, and a second
# implementation here is a second thing to drift -- which is the fault this script exists to fix.
#
# Not named `sh`: under `rails runner` that resolves to Rake's `FileUtils#sh`, which echoes the
# command and returns `true` rather than its output -- so every figure came back as `true`.
def capture(cmd)
  `#{cmd} 2>/dev/null`
end

def count(cmd) = capture(cmd).strip.to_i

status = capture("ruby #{Rails.root.join("bin/design/status.rb")}")
controllers = status[/controllers on design system:\s*(\d+ \/ \d+)/, 1]&.tr("/", "o")&.sub("o", "of")
views = status[/views with design-system markup:\s*(\d+ \/ \d+)/, 1]&.tr("/", "o")&.sub("o", "of")

routes_out = capture("cd #{Rails.root} && bin/rails runner bin/design/dead-routes.rb")
routes_total = routes_out[/(\d+) routes checked/, 1]
routes_dead = routes_out[/(\d+) dead/, 1]

dead_code = capture("cd #{Rails.root} && bin/rails runner bin/design/dead-code.rb")[/(\d+) finding/, 1]

undefined_classes = capture("cd #{Rails.root} && python3 bin/design/undefined-classes.py")
undefined_count = undefined_classes.include?("reports zero") ? 0 : undefined_classes.scan(/^\s+\S+$/).size

# `1,078` not `1078`: the table has always delimited these, so a diff is about the figure changing
# rather than about formatting.
def delimit(n) = n.to_s.reverse.scan(/\d{1,3}/).join(",").reverse

# **Says `n/a` rather than 0 when `main` is not there.** CI checks out shallow, so `main..HEAD`
# resolves to nothing and `capture` swallows the error -- which would have printed "0 commits on the
# branch" with a straight face. A figure that cannot be computed has to say so; the alternative is
# the quiet kind of wrong this whole script exists to stop.
have_main = system("git -C #{Rails.root} rev-parse --verify --quiet main > /dev/null 2>&1")
against_main = lambda { |cmd|
  have_main ? delimit(count(cmd)) : "n/a (no `main` ref -- shallow clone)"
}

rows = {
  "Commits on the branch" =>
    against_main.call("git -C #{Rails.root} rev-list --count main..HEAD"),
  "Files changed against `main`" =>
    against_main.call("git -C #{Rails.root} diff --name-only main...HEAD | wc -l"),
  "Controllers on a design system layout" => controllers,
  "Views carrying design system markup" => views,
  "Stimulus controllers" => Rails.root.glob("app/javascript/controllers/*_controller.js").size.to_s,
  "Undefined legacy classes left in `app/views`" => undefined_count.to_s,
  "Routes whose request would raise" => "#{routes_dead} of #{routes_total}",
  "Code no route, render or caller reaches" => "#{dead_code} findings, documented in design-decisions.md"
}

sha = capture("git -C #{Rails.root} rev-parse --short HEAD").strip
table = "#{BEGIN_MARK}\n"
table << "Generated by `bin/rails runner bin/design/state.rb` on " \
         "#{Time.zone.today.iso8601} at `#{sha}`. Do not edit by hand.\n\n"
table << "| | |\n| --- | --- |\n"
rows.each { |k, v| table << "| #{k} | #{v} |\n" }
table << END_MARK

doc = CHANGELOG.read
unless doc.include?(BEGIN_MARK) && doc.include?(END_MARK)
  abort "docs/changelog.md has no #{BEGIN_MARK} / #{END_MARK} markers"
end

updated = doc.sub(/#{Regexp.escape(BEGIN_MARK)}.*?#{Regexp.escape(END_MARK)}/mo, table)

# Rows that are *expected* to move on every commit. They give a sense of scale and are worth
# printing, but gating on them would fail every pull request for a reason nobody can act on -- which
# is how a check gets switched off.
VOLATILE = ["Commits on the branch", "Files changed against `main`"].freeze

if ARGV.include?("--check")
  # The date and sha move on every commit too, so compare rows only, and only the ones that mean
  # something. What must not drift silently is the migration state: how many controllers are on the
  # layout, how many views carry the markup, whether a route raises.
  strip = lambda { |t|
    t.scan(/^\| ([^|]+) \| ([^|]+) \|$/)
      .reject { |k, _| VOLATILE.include?(k.strip) || k.strip == "---" }
      .map { |k, v| "#{k.strip}|#{v.strip}" }.join("\n")
  }
  if strip.call(doc[/#{Regexp.escape(BEGIN_MARK)}.*?#{Regexp.escape(END_MARK)}/mo].to_s) == strip.call(table)
    puts "current state table is up to date"
    exit 0
  end
  puts "current state table is out of date; run: bin/rails runner bin/design/state.rb"
  puts table
  exit 1
end

CHANGELOG.write(updated)
puts table
